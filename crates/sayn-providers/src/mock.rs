use crate::error::ProviderError;
use crate::provider::{GeneratedFile, GenerationRequest, GenerationResponse, Provider};
use std::path::PathBuf;

pub struct MockProvider {
    pub provider_name: String,
}

impl Default for MockProvider {
    fn default() -> Self {
        Self {
            provider_name: "mock-hermes".to_string(),
        }
    }
}

impl MockProvider {
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            provider_name: name.into(),
        }
    }
}

impl Provider for MockProvider {
    fn name(&self) -> &str {
        &self.provider_name
    }

    fn generate(&self, request: &GenerationRequest) -> Result<GenerationResponse, ProviderError> {
        let page_tsx = format!(
            r#"// Generated by {}
export default function Page() {{
  return (
    <div style={{{{ padding: '2rem' }}}}>
      <h1>Generated Application</h1>
      <p>Target: {}</p>
    </div>
  );
}}
"#,
            self.provider_name, request.target
        );

        let files = vec![
            GeneratedFile {
                relative_path: PathBuf::from("app/page.tsx"),
                content: page_tsx,
            },
            GeneratedFile {
                relative_path: PathBuf::from("package.json"),
                content: r#"{"name": "generated-mock", "version": "0.1.0"}"#.to_string(),
            },
        ];

        Ok(GenerationResponse {
            files,
            summary: "Mock generation completed successfully".to_string(),
            input_tokens: 150,
            output_tokens: 320,
        })
    }
}
